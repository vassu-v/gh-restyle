// Runs after `expo export --platform web`. Turns apps/app/dist into an installable, offline-capable PWA:
//   1. adds manifest / icon / theme meta tags to index.html (Expo's single-page output has no HTML template hook)
//   2. writes sw.js with a precache list of this build's files and a build-specific cache name
//   0. renames asset folders that start with "@" (scoped packages, e.g. @expo-google-fonts): Cloudflare's asset
//      server redirects %40 ↔ @ forever (ERR_TOO_MANY_REDIRECTS), so fonts never loaded in production
// Idempotent: running it twice gives the same result.
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

const dist = fileURLToPath(new URL('../apps/app/dist/', import.meta.url));
const walkAll = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? [p, ...walkAll(p)] : [p]; });

// 0. "@" in asset paths → "_at_", in folder names and in every "/assets/…" string in the JS/HTML.
for (const d of walkAll(join(dist, 'assets')).filter((p) => statSync(p).isDirectory() && basename(p).startsWith('@')).sort((a, b) => b.length - a.length)) {
  renameSync(d, join(d, '..', '_at_' + basename(d).slice(1)));
}
for (const f of walkAll(dist).filter((p) => /\.(js|html)$/.test(p))) {
  const src = readFileSync(f, 'utf8');
  const out = src.replace(/(["'`])\/assets\/[^"'`]*\1/g, (m) => m.replace(/\/@/g, '/_at_'));
  if (out !== src) writeFileSync(f, out);
}

const htmlPath = join(dist, 'index.html');
let html = readFileSync(htmlPath, 'utf8');

const HEAD = `
    <!-- gitling:pwa -->
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="Gitling" />
    <meta name="description" content="A GitHub client whose interface you design yourself." />
    <style>html, body { background: #0E0F11; }</style>
    <script>/* Catch the install prompt before the app bundle loads; src/pwa/register.ts picks it up. */
      addEventListener('beforeinstallprompt', function (e) { e.preventDefault(); window.__gitlingInstall = e; });</script>
    <!-- /gitling:pwa -->`;
html = html.replace(/\n\s*<!-- gitling:pwa -->[\s\S]*?<!-- \/gitling:pwa -->/, '');
html = html.replace('</head>', `${HEAD}\n</head>`);
// viewport-fit=cover lets the app draw under the notch; safe-area insets keep content clear of it.
html = html.replace(/<meta name="viewport" content="[^"]*"\s*\/?>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />');
writeFileSync(htmlPath, html);

const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
// Files with "@" in the name (library icons like close-icon@2x.png) can't be fetched from Cloudflare's asset
// server (it redirects %40 <-> @ forever), and one failed file makes the whole service-worker install fail.
// The app never loads them, so they stay out of the precache.
const skip = /(^|\/)(sw\.js|_redirects|_headers|metadata\.json|\.DS_Store)$|\.map$|@/;
const files = walk(dist).map((p) => '/' + relative(dist, p).split('\\').join('/')).filter((p) => !skip.test(p)).sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = 'gitling-' + hash.digest('hex').slice(0, 12);
const precache = files.filter((f) => f !== '/index.html').concat('/');

const sw = `// Generated by scripts/pwa.mjs — do not edit. Cache: ${version}
const CACHE = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
// Keep the two previous builds too: an app that was open during a deploy still loads its own (old) code chunks.
// caches.keys() lists caches in creation order, so everything before the last three is old.
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => { const ours = keys.filter((k) => k.startsWith('gitling-')); return Promise.all(ours.slice(0, Math.max(0, ours.length - 3)).map((k) => caches.delete(k))); }).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  // Only this site's own files. GitHub API calls are never cached here (the app has its own ETag cache).
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // App shell: network first so deploys show up, cached shell when offline.
    e.respondWith(fetch(req).catch(() => caches.match('/', { cacheName: CACHE }).then((r) => r || caches.match('/'))));
    return;
  }
  // This build's cache first. Older caches only for hashed chunks (an old open tab may still ask for them);
  // unhashed files (manifest, icons) from an older build would be stale.
  const hashed = url.pathname.startsWith('/_expo/static/');
  e.respondWith(caches.match(req, { cacheName: CACHE }).then((hit) => hit || (hashed ? caches.match(req) : undefined)).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok && hashed) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

// Content-Security-Policy for Cloudflare (dist/_headers). The inline install-prompt script is allowed by hash,
// so no 'unsafe-inline' for scripts: javascript: URLs and injected <script> can't run. react-native-web injects
// <style> tags, hence 'unsafe-inline' for styles. Markdown images may come from any https host.
const shell = readFileSync(join(dist, 'index.html'), 'utf8');
const hashes = [...shell.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`);
const authOrigin = (() => { try { return new URL(process.env.EXPO_PUBLIC_AUTH_URL ?? '').origin; } catch { return ''; } })();
const csp = [
  "default-src 'self'", `script-src 'self' ${hashes.join(' ')}`.trim(), "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:", "font-src 'self' data:", `connect-src 'self' https://api.github.com https://raw.githubusercontent.com ${authOrigin}`.trim(),
  "worker-src 'self'", "manifest-src 'self'", "object-src 'none'", "base-uri 'self'", "form-action 'self'", "frame-ancestors 'none'",
].join('; ');
const headersFile = join(dist, '_headers');
if (existsSync(headersFile)) writeFileSync(headersFile, readFileSync(headersFile, 'utf8').replace(/^\/\*\r?\n/m, (m) => `${m}  Content-Security-Policy: ${csp}\n`));
console.log(`pwa: ${precache.length} files precached as ${version}`);
