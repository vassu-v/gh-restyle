// Runs after `expo export --platform web`. Turns apps/app/dist into an installable, offline-capable PWA:
//   1. adds manifest / icon / theme meta tags to index.html (Expo's single-page output has no HTML template hook)
//   2. writes sw.js with a precache list of this build's files and a build-specific cache name
//   0. renames asset folders that start with "@" (scoped packages, e.g. @expo-google-fonts): Cloudflare's asset
//      server redirects %40 ↔ @ forever (ERR_TOO_MANY_REDIRECTS), so fonts never loaded in production
// Idempotent: running it twice gives the same result.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../apps/app/dist/', import.meta.url).pathname;
const walkAll = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? [p, ...walkAll(p)] : [p]; });

// 0. "@" in asset paths → "_at_", in folder names and in every "/assets/…" string in the JS/HTML.
for (const d of walkAll(join(dist, 'assets')).filter((p) => statSync(p).isDirectory() && p.split('/').pop().startsWith('@')).sort((a, b) => b.length - a.length)) {
  renameSync(d, join(d, '..', '_at_' + d.split('/').pop().slice(1)));
}
for (const f of walkAll(dist).filter((p) => /\.(js|html)$/.test(p))) {
  const src = readFileSync(f, 'utf8');
  const out = src.replace(/(["'`])\/assets\/[^"'`]*\1/g, (m) => m.replace(/\/@/g, '/_at_'));
  if (out !== src) writeFileSync(f, out);
}

const htmlPath = join(dist, 'index.html');
let html = readFileSync(htmlPath, 'utf8');

const HEAD = `
    <!-- gitling:pwa -->
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="Gitling" />
    <meta name="description" content="A GitHub client whose interface you design yourself." />
    <style>html, body { background: #0E0F11; }</style>
    <!-- /gitling:pwa -->`;
html = html.replace(/\n\s*<!-- gitling:pwa -->[\s\S]*?<!-- \/gitling:pwa -->/, '');
html = html.replace('</head>', `${HEAD}\n</head>`);
// viewport-fit=cover lets the app draw under the notch; safe-area insets keep content clear of it.
html = html.replace(/<meta name="viewport" content="[^"]*"\s*\/?>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />');
writeFileSync(htmlPath, html);

const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const skip = /(^|\/)(sw\.js|_redirects|_headers|metadata\.json|\.DS_Store)$|\.map$/;
const files = walk(dist).map((p) => '/' + relative(dist, p).split('\\').join('/')).filter((p) => !skip.test(p)).sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = 'gitling-' + hash.digest('hex').slice(0, 12);
const precache = files.filter((f) => f !== '/index.html').concat('/');

const sw = `// Generated by scripts/pwa.mjs — do not edit. Cache: ${version}
const CACHE = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  // Only this site's own files. GitHub API calls are never cached here (the app has its own ETag cache).
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // App shell: network first so deploys show up, cached shell when offline.
    e.respondWith(fetch(req).catch(() => caches.match('/', { cacheName: CACHE })));
    return;
  }
  e.respondWith(caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok && url.pathname.startsWith('/_expo/static/')) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`pwa: ${precache.length} files precached as ${version}`);
